func TestGenPropsGenerateAll_SuccessAndIdempotent(t *testing.T) {
	outDir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(outDir, "ignored_test.go"), []byte("package ignored\n"), 0644))
	require.NoError(t, os.WriteFile(filepath.Join(outDir, "notes.txt"), []byte("plain text"), 0644))
	require.NoError(t, os.WriteFile(filepath.Join(outDir, "invalid.go"), []byte("var broken = 1\n"), 0644))
	require.NoError(t, os.Mkdir(filepath.Join(outDir, "nested"), 0755))
	require.NoError(t, os.Symlink(filepath.Join(outDir, "missing.go"), filepath.Join(outDir, "broken_link.go")))

	logCalls := 0
	g := genprops.New(
		genprops.WithOutputDir(outDir),
		genprops.WithOutputFile("custom_props.go"),
		genprops.WithPackageName("model"),
		genprops.WithNamingStrategy(schema.NamingStrategy{SingularTable: true}),
		genprops.WithLogger(func(format string, args ...interface{}) {
			logCalls++
		}),
	)

	err := g.GenerateAll([]any{&model.User{}, &model.User{}})
	require.NoError(t, err)

	content, err := os.ReadFile(filepath.Join(outDir, "custom_props.go"))
	require.NoError(t, err)

	generated := string(content)
	assert.Contains(t, generated, "Code generated by genprops. DO NOT EDIT.")
	assert.Contains(t, generated, "package model")
	assert.Contains(t, generated, "var UserProps = struct")
	assert.Contains(t, generated, "UserName  query.Column")
	assert.Contains(t, generated, "DeletedAt query.Column")
	assert.Contains(t, generated, `UserName:  "user_name"`)
	assert.Contains(t, generated, `import query "github.com/im-wmkong/gorm-query/query"`)
	assert.Equal(t, 1, strings.Count(generated, "var UserProps = struct"))
	assert.Equal(t, 1, logCalls)

	err = g.GenerateAll([]any{&model.User{}})
	require.NoError(t, err)
	assert.Equal(t, 1, logCalls)
}

func TestGenPropsGenerateAll_WithExplicitPackageNameForMixedModels(t *testing.T) {
	outDir := t.TempDir()

	err := genprops.New(
		genprops.WithOutputDir(outDir),
		genprops.WithOutputFile("mixed_props.go"),
		genprops.WithPackageName("model"),
	).GenerateAll([]any{&model.User{}, &localGenPropsModel{}})
	require.NoError(t, err)

	content, err := os.ReadFile(filepath.Join(outDir, "mixed_props.go"))
	require.NoError(t, err)

	generated := string(content)
	assert.Contains(t, generated, "UserProps defines the fields for User")
	assert.Contains(t, generated, "localGenPropsModelProps defines the fields for localGenPropsModel")
	assert.Contains(t, generated, "var localGenPropsModelProps = struct")
	assert.Contains(t, generated, `ID: "id"`)
}

