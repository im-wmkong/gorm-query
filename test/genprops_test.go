func TestGenPropsGenerate_DryRun(t *testing.T) {
	outDir := t.TempDir()

	g := genprops.New(genprops.WithOutputDir(outDir))
	require.NoError(t, g.Generate(&model.User{}))

	dryRunGenerator := genprops.New(
		genprops.WithOutputDir(outDir),
		genprops.WithDryRun(true),
	)
	require.NoError(t, dryRunGenerator.Generate(&model.User{}))

	propsFile := filepath.Join(outDir, "props_gen.go")
	require.NoError(t, os.WriteFile(propsFile, []byte("package model\n"), 0644))

	err := dryRunGenerator.Generate(&model.User{})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "generated file outdated")
	assert.Contains(t, err.Error(), propsFile)
}

func TestGenPropsGenerateAll_ErrorScenarios(t *testing.T) {
	t.Run("no models", func(t *testing.T) {
		err := genprops.New().GenerateAll(nil)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "no models provided")
	})

	t.Run("mixed packages without explicit package name", func(t *testing.T) {
		err := genprops.New(genprops.WithOutputDir(t.TempDir())).GenerateAll([]any{&model.User{}, &localGenPropsModel{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "all models must be in the same package")
	})

	t.Run("package mismatch in output dir", func(t *testing.T) {
		outDir := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(outDir, "existing.go"), []byte("// generated elsewhere\n\npackage otherpkg\n"), 0644))

		err := genprops.New(
			genprops.WithOutputDir(outDir),
			genprops.WithPackageName("model"),
		).GenerateAll([]any{&model.User{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "package mismatch")
	})

	t.Run("create output dir failed", func(t *testing.T) {
		baseDir := t.TempDir()
		blockedPath := filepath.Join(baseDir, "blocked")
		require.NoError(t, os.WriteFile(blockedPath, []byte("not a directory"), 0644))

		err := genprops.New(genprops.WithOutputDir(blockedPath)).GenerateAll([]any{&model.User{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "create output dir failed")
	})

	t.Run("write file failed", func(t *testing.T) {
		outDir := t.TempDir()

		err := genprops.New(
			genprops.WithOutputDir(outDir),
			genprops.WithOutputFile(filepath.Join("nested", "props_gen.go")),
		).GenerateAll([]any{&model.User{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "write file failed")
	})

	t.Run("detect package failed", func(t *testing.T) {
		outDir := filepath.Join(t.TempDir(), "locked")
		require.NoError(t, os.Mkdir(outDir, 0000))
		defer os.Chmod(outDir, 0755)

		err := genprops.New(
			genprops.WithOutputDir(outDir),
			genprops.WithPackageName("model"),
		).GenerateAll([]any{&model.User{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "detect package failed")
	})

	t.Run("schema parse failed", func(t *testing.T) {
		err := genprops.New(
			genprops.WithOutputDir(t.TempDir()),
			genprops.WithPackageName("broken"),
		).GenerateAll([]any{123})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "gorm schema parse failed")
	})

	t.Run("render failed", func(t *testing.T) {
		err := genprops.New(
			genprops.WithOutputDir(t.TempDir()),
			genprops.WithPackageName("invalid-package"),
		).GenerateAll([]any{&model.User{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "render failed")
	})
}

func TestDetectPackageName(t *testing.T) {
	t.Run("finds package after comments and blank lines", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(dir, "model.go"), []byte("// comment\n\npackage sample\n"), 0644))

		pkg, err := linkedDetectPackageName(dir)
		require.NoError(t, err)
		assert.Equal(t, "sample", pkg)
	})

	t.Run("skips test files broken links and invalid go files", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(dir, "helper_test.go"), []byte("package ignored\n"), 0644))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "notes.txt"), []byte("plain text"), 0644))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "broken.go"), []byte("var x = 1\n"), 0644))
		require.NoError(t, os.Symlink(filepath.Join(dir, "missing.go"), filepath.Join(dir, "missing_link.go")))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "real.go"), []byte("package actual\n"), 0644))

		pkg, err := linkedDetectPackageName(dir)
		require.NoError(t, err)
		assert.Equal(t, "actual", pkg)
	})

	t.Run("returns empty when no package exists", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(dir, "broken.go"), []byte("var x = 1\n"), 0644))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "helper_test.go"), []byte("package ignored\n"), 0644))

		pkg, err := linkedDetectPackageName(dir)
		require.NoError(t, err)
		assert.Empty(t, pkg)
	})

	t.Run("returns error for missing dir", func(t *testing.T) {
		pkg, err := linkedDetectPackageName(filepath.Join(t.TempDir(), "missing"))
		require.Error(t, err)
		assert.Empty(t, pkg)
	})
}
