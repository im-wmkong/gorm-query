func TestGenerateSchema_ErrorScenarios(t *testing.T) {
	t.Run("no models", func(t *testing.T) {
		err := New().Generate(nil)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "no models provided")
	})

	t.Run("WithLogger nil does not panic", func(t *testing.T) {
		g := New(
			WithOutputDir(t.TempDir()),
			WithPackageName("model"),
			WithLogger(nil),
		)
		err := g.Generate(&user{})
		require.NoError(t, err)
	})

	t.Run("mixed packages without explicit package name", func(t *testing.T) {
		// Use an anonymous struct as the second arg (reflect.Type.PkgPath() == "") to trigger
		// the "no package path" validation without depending on example/model.
		err := New(WithOutputDir(t.TempDir())).Generate(&user{}, &struct{ ID uint }{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "no package path")
	})

	t.Run("package mismatch in output dir", func(t *testing.T) {
		outDir := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(outDir, "existing.go"), []byte("// generated elsewhere\n\npackage otherpkg\n"), 0644))

		err := New(
			WithOutputDir(outDir),
			WithPackageName("model"),
		).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "package mismatch")
	})

	t.Run("create output dir failed", func(t *testing.T) {
		baseDir := t.TempDir()
		blockedPath := filepath.Join(baseDir, "blocked")
		require.NoError(t, os.WriteFile(blockedPath, []byte("not a directory"), 0644))

		err := New(WithOutputDir(blockedPath)).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "create output dir failed")
	})

	t.Run("detect package failed", func(t *testing.T) {
		outDir := filepath.Join(t.TempDir(), "locked")
		require.NoError(t, os.Mkdir(outDir, 0000))
		t.Cleanup(func() {
			require.NoError(t, os.Chmod(outDir, 0755))
		})

		err := New(
			WithOutputDir(outDir),
			WithPackageName("model"),
		).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "detect package failed")
	})

	t.Run("schema parse failed", func(t *testing.T) {
		err := New(
			WithOutputDir(t.TempDir()),
			WithPackageName("broken"),
		).Generate(123)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "gorm schema parse failed")
	})

	t.Run("render failed", func(t *testing.T) {
		err := New(
			WithOutputDir(t.TempDir()),
			WithPackageName("invalid-package"),
		).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "render failed")
	})

	t.Run("package name resolution failed", func(t *testing.T) {
		// outputDir ends with an invalid Go identifier and no explicit package name,
		// so packageName() returns an error.
		outDir := filepath.Join(t.TempDir(), "invalid-dir")
		require.NoError(t, os.MkdirAll(outDir, 0755))

		err := New(WithOutputDir(outDir)).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "unable to resolve package name")
	})

	t.Run("target path is a directory", func(t *testing.T) {
		outDir := t.TempDir()
		// Create a directory at the target file path so both os.ReadFile and os.WriteFile fail.
		require.NoError(t, os.Mkdir(filepath.Join(outDir, "user_gen.go"), 0755))

		err := New(
			WithOutputDir(outDir),
			WithPackageName("model"),
		).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "read existing file")
		assert.Contains(t, err.Error(), "failed")
	})

	t.Run("write file failed on read-only dir", func(t *testing.T) {
		baseDir := t.TempDir()
		outDir := filepath.Join(baseDir, "readonly")
		require.NoError(t, os.Mkdir(outDir, 0755))
		// Make the directory read-only so os.ReadFile returns ErrNotExist (treated as "exists=false"),
		// while os.WriteFile fails with a permission error.
		require.NoError(t, os.Chmod(outDir, 0555))
		t.Cleanup(func() {
			_ = os.Chmod(outDir, 0755)
		})

		err := New(
			WithOutputDir(outDir),
			WithPackageName("model"),
		).Generate(&user{})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "write file")
		assert.Contains(t, err.Error(), "failed")
	})
}

