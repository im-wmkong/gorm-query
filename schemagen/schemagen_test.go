func TestGenerateSchema_DryRun(t *testing.T) {
	outDir := t.TempDir()

	g := New(WithOutputDir(outDir), WithPackageName("schemagen"))
	require.NoError(t, g.Generate(&User{}))

	dryRunGenerator := New(
		WithOutputDir(outDir),
		WithPackageName("schemagen"),
		WithDryRun(true),
	)
	require.NoError(t, dryRunGenerator.Generate(&User{}))

	generatedFile := filepath.Join(outDir, "user_gen.go")
	// Overwrite the generated file with different content so dry-run detects it's outdated.
	require.NoError(t, os.WriteFile(generatedFile, []byte("package schemagen\n"), 0644))

	err := dryRunGenerator.Generate(&User{})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "generated file outdated")
	assert.Contains(t, err.Error(), generatedFile)
}

