type User struct {
	gorm.Model
	UserName string `gorm:"column:user_name;size:255;not null"`
	Email    string `gorm:"column:email;size:255;unique"`
	Age      int    `gorm:"column:age"`
	Status   int    `gorm:"column:status;default:1"` // 1: active, 0: inactive
}

type LocalSchemaModel struct {
	ID uint
}

type EmptySchemaModel struct{}

type unexportedSchemaModel struct {
	ID uint
}

func TestGenerateSchema_SuccessAndIdempotent(t *testing.T) {
	outDir := t.TempDir()

	g := New(
		WithOutputDir(outDir),
		WithPackageName("schemagen"),
		WithNamingStrategy(schema.NamingStrategy{SingularTable: true}),
		WithLogger(nil),
	)

	err := g.Generate(nil, &User{}, &User{})
	require.NoError(t, err)

	content, err := os.ReadFile(filepath.Join(outDir, "user_gen.go"))
	require.NoError(t, err)

	generated := string(content)
	assert.Contains(t, generated, "Code generated by schemagen. DO NOT EDIT.")
	assert.Contains(t, generated, "package schemagen")

	err = g.Generate(&User{})
	require.NoError(t, err)
	again, err := os.ReadFile(filepath.Join(outDir, "user_gen.go"))
	require.NoError(t, err)
	assert.Equal(t, content, again, "regeneration must preserve file content")
}

func TestGenerateSchema_WithExplicitPackageNameForMixedModels(t *testing.T) {
	outDir := t.TempDir()

	err := New(
		WithOutputDir(outDir),
		WithPackageName("schemagen"),
		WithNamingStrategy(schema.NamingStrategy{SingularTable: true}),
	).Generate(&User{}, &LocalSchemaModel{})
	require.NoError(t, err)

	userContent, err := os.ReadFile(filepath.Join(outDir, "user_gen.go"))
	require.NoError(t, err)
	localContent, err := os.ReadFile(filepath.Join(outDir, "local_schema_model_gen.go"))
	require.NoError(t, err)

	assert.Contains(t, string(userContent), "package schemagen")
	assert.Contains(t, string(localContent), "package schemagen")
	assert.NotEqual(t, string(userContent), string(localContent))
}

