type user struct {
	gorm.Model
	UserName string `gorm:"column:user_name;size:255;not null"`
	Email    string `gorm:"column:email;size:255;unique"`
	Age      int    `gorm:"column:age"`
	Status   int    `gorm:"column:status;default:1"` // 1: active, 0: inactive
}

type localSchemaModel struct {
	ID uint
}

type emptySchemaModel struct{}

type partiallyIgnoredSchemaModel struct {
	ID      uint
	Name    string `gorm:"column:name"`
	Ignored string `gorm:"-"`
}

type testLogger struct {
	infoCalls  int
	debugCalls int
	warnCalls  int
}

func (l *testLogger) Debug(string, ...any) { l.debugCalls++ }
func (l *testLogger) Info(string, ...any)  { l.infoCalls++ }
func (l *testLogger) Warn(string, ...any)  { l.warnCalls++ }

func TestFilterNilModels(t *testing.T) {
	filtered, nilCount := New().filterNilModels([]any{nil, &user{}, nil, &localSchemaModel{}})
	require.Len(t, filtered, 2)
	assert.Equal(t, 2, nilCount)
	assert.IsType(t, &user{}, filtered[0])
	assert.IsType(t, &localSchemaModel{}, filtered[1])
}

func TestGeneratorResolvePackageName(t *testing.T) {
	t.Run("explicit package name wins", func(t *testing.T) {
		g := New(WithPackageName("model"))
		pkgName, err := g.packageName()
		require.NoError(t, err)
		assert.Equal(t, "model", pkgName)
	})

	t.Run("inferred from default output dir", func(t *testing.T) {
		g := New()
		pkgName, err := g.packageName()
		require.NoError(t, err)
		assert.Equal(t, "schema", pkgName)
	})

	t.Run("inferred from custom output dir", func(t *testing.T) {
		g := New(WithOutputDir("./path/to/mypkg"))
		pkgName, err := g.packageName()
		require.NoError(t, err)
		assert.Equal(t, "mypkg", pkgName)
	})

	t.Run("fails when output dir is not a valid identifier", func(t *testing.T) {
		g := New(WithOutputDir("./invalid-dir"))
		_, err := g.packageName()
		require.Error(t, err)
		assert.Contains(t, err.Error(), "unable to resolve package name")
	})
}

func TestGeneratorCheckSameModelPackage(t *testing.T) {
	g := New()

	t.Run("single model passes", func(t *testing.T) {
		require.NoError(t, g.checkSamePackage([]any{&user{}}))
	})

	t.Run("empty slice passes", func(t *testing.T) {
		require.NoError(t, g.checkSamePackage(nil))
	})

	t.Run("same package passes", func(t *testing.T) {
		require.NoError(t, g.checkSamePackage([]any{&user{}, &localSchemaModel{}}))
	})

	t.Run("anonymous struct fails with no package path", func(t *testing.T) {
		err := g.checkSamePackage([]any{&user{}, &struct{ ID uint }{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "no package path")
	})

	t.Run("first model has no package path", func(t *testing.T) {
		err := g.checkSamePackage([]any{&struct{ ID uint }{}, &user{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "no package path")
	})

	t.Run("different real packages fail", func(t *testing.T) {
		// schemagen.user and example/model.User live in different real packages.
		err := g.checkSamePackage([]any{&user{}, &model.User{}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "all models must be in the same package")
	})
}

func TestGenerateSchema_SuccessAndIdempotent(t *testing.T) {
	outDir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(outDir, "ignored_test.go"), []byte("package ignored\n"), 0644))
	require.NoError(t, os.WriteFile(filepath.Join(outDir, "notes.txt"), []byte("plain text"), 0644))
	require.NoError(t, os.WriteFile(filepath.Join(outDir, "invalid.go"), []byte("var broken = 1\n"), 0644))
	require.NoError(t, os.Mkdir(filepath.Join(outDir, "nested"), 0755))
	require.NoError(t, os.Symlink(filepath.Join(outDir, "missing.go"), filepath.Join(outDir, "broken_link.go")))

	tl := &testLogger{}
	g := New(
		WithOutputDir(outDir),
		WithPackageName("model"),
		WithNamingStrategy(schema.NamingStrategy{SingularTable: true}),
		WithLogger(tl),
	)

	err := g.Generate(&user{}, &user{})
	require.NoError(t, err)

	content, err := os.ReadFile(filepath.Join(outDir, "user_gen.go"))
	require.NoError(t, err)

	generated := string(content)
	assert.Contains(t, generated, "Code generated by schemagen. DO NOT EDIT.")
	assert.Contains(t, generated, "package model")
	assert.Contains(t, generated, "var user = struct")
	assert.Contains(t, generated, "UserName")
	assert.Contains(t, generated, "query.Column")
	assert.Contains(t, generated, "DeletedAt query.Column")
	assert.Contains(t, generated, `UserName:  "user_name"`)
	assert.Contains(t, generated, `import query "github.com/im-wmkong/gorm-query/query"`)

	// First run: Info contains "generating schema..." and "generated ...".
	assert.Equal(t, 2, tl.infoCalls)
	// Duplicate user triggers one Warn.
	assert.Equal(t, 1, tl.warnCalls)
	assert.Greater(t, tl.debugCalls, 0)

	prevInfo := tl.infoCalls
	err = g.Generate(&user{})
	require.NoError(t, err)
	// Idempotent: unchanged content skips writing; only Debug is emitted.
	// Info should not increase except "generating schema...".
	assert.Equal(t, prevInfo+1, tl.infoCalls)
}

